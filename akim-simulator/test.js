assert.ok(Math.abs(baseline.score-52.56)<.02);assert.ok(r.score>baseline.score);
assert.ok(r.contributions.some(c=>c.source==='M10+M12'&&c.district==='Нура'&&c.delta===2));
assert.ok(validate(example.slice(0,4)).length);assert.ok(validate([...example,{id:'M9',district:'Нура'}]).length);
assert.ok(validate([{id:'M1',district:'Нура'},{id:'M3',district:'Есиль'}],false).length);
assert.ok(validate([{id:'M4',district:'Нура'},{id:'M7',district:'Нура'}],false).length);
