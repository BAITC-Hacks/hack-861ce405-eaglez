const assert=require('node:assert/strict');const {calculate,baseline,validate}=require('./engine');
const example=[['M7','Нура'],['M8','Нура'],['M10','Нура'],['M12',null],['M5','Сарыарка']].map(([id,district])=>({id,district}));
